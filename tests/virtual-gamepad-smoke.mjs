import { _electron as electron, expect } from '@playwright/test';
import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';
import { VirtualGamepad } from '../src/input/virtual-gamepad.ts';
import { NativeWindows } from '../src/capture/native-window.ts';

const temp = await mkdtemp(join(tmpdir(), 'gamepilot-pad-'));
await writeFile(join(temp, 'package.json'), JSON.stringify({ main: 'index.cjs' }));
await writeFile(join(temp, 'index.cjs'), `const {app,BrowserWindow}=require('electron');app.whenReady().then(()=>{const w=new BrowserWindow({width:500,height:350});w.loadURL('data:text/html,<h1>GamePilot XInput acceptance</h1>');});app.on('window-all-closed',()=>app.quit());`);
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
const native = new NativeWindows(resolve('dist/capture/native-window.ps1'));
const bridge = new VirtualGamepad(resolve('.'));
let target, latest = [], samples = [];
const observer = spawn(resolve('.venv/Scripts/python.exe'), ['-u', resolve('tests/xinput-probe.py')], { windowsHide: true, stdio: 'pipe' });
observer.stderr.resume();
createInterface({ input: observer.stdout }).on('line', line => { latest = JSON.parse(line); samples.push(...latest); });
try {
  target = await electron.launch({ args: [temp], env }); await target.firstWindow();
  const source = await target.evaluate(({ BrowserWindow }) => `window:${BrowserWindow.getAllWindows()[0].getNativeWindowHandle().readBigUInt64LE()}:0`);
  const info = await native.info(source); await native.focus(source, info.identity);
  await bridge.connect();
  assert.equal(bridge.connected, true);
  await expect.poll(() => latest.length, { timeout: 5000 }).toBeGreaterThan(0);
  samples = [];
  const receipt = await bridge.action(source, info.identity, { buttons: ['A'], left_x: 0.6, right_y: -0.4, left_trigger: 0.5, duration_ms: 400 }, new AbortController().signal);
  assert.equal(receipt.released, true);
  const active = samples.find(s => (s.buttons & 0x1000) && s.lx > 19000 && s.ry < -12000 && s.lt > 120);
  assert.ok(active, 'Windows XInput must report actual button, sticks and trigger values');
  const neutral = () => latest.find(s => s.index === active.index);
  await expect.poll(() => neutral() && Object.entries(neutral()).every(([k,v]) => k === 'index' || v === 0)).toBe(true);
  const controller = new AbortController(); samples = [];
  const action = bridge.action(source, info.identity, { buttons: ['B'], duration_ms: 1000 }, controller.signal);
  const canceled = assert.rejects(action);
  await expect.poll(() => samples.some(s => s.buttons & 0x2000), { intervals: [20] }).toBe(true);
  controller.abort(); await canceled; await bridge.close();
  await expect.poll(() => !latest.some(s => s.index === active.index && (s.buttons || s.lx || s.ly || s.rx || s.ry || s.lt || s.rt))).toBe(true);
  await bridge.connect();
  await native.focus(source, info.identity); samples = [];
  const focusAction = bridge.action(source, info.identity, { buttons: ['X'], duration_ms: 1000 }, new AbortController().signal);
  const interrupted = assert.rejects(focusAction, /focus|identity/);
  await expect.poll(() => samples.some(s => s.buttons & 0x4000), { intervals: [20] }).toBe(true);
  await target.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].minimize());
  await interrupted;
  await expect.poll(() => !latest.some(s => s.buttons & 0x4000)).toBe(true);
  await assert.rejects(bridge.action(source, info.identity, { buttons: ['A'], duration_ms: 100 }, new AbortController().signal), /focus|identity/);
  await mkdir('artifacts', { recursive: true });
  await writeFile('artifacts/virtual-gamepad-check.json', JSON.stringify({ passed: true, backend: 'real ViGEmBus Xbox360', observedBy: 'Windows XInputGetState', activeReport: active, released: true, canceledNeutral: true, minimizedBlocked: true, focusLossReleased: true }, null, 2));
  console.log('PASS: real XInput button/sticks/trigger observed; release, cancellation and focus guard verified.');
} finally { await bridge.close(); native.close(); observer.kill(); await target?.close(); await rm(temp, { recursive: true, force: true }); }
